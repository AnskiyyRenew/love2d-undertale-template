# -*- coding: utf-8 -*-
"""
Generates the obfuscated C source for the native secret store.

Reads plaintext secrets from a local JSON file and emits a .c file in which no
secret appears as a string literal. Two layers are applied:

  1. Every byte is XOR-ed with a per-index mask derived from a random seed, so
     the stored immediates are not the plaintext.
  2. The bytes are emitted as one assignment statement each inside a fill
     function instead of a static array, so nothing lands in .rodata -- a
     `strings` pass over the binary finds no blob at all, only code.

The library is still only obfuscation: anyone with a disassembler can read the
fill function. It exists to stop a curious player from unzipping game.love and
reading the key in plain text. See README.md for the honest threat model.

Usage:
    python gen_source.py --input secrets.local.json --output build/secrets.c
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys

# Slot order is part of the binary contract: index == position here.
# Secrets.lua mirrors this as SLOT_* constants. Append only, never reorder.
SLOT_ORDER = ("gamejolt_pk", "reserved_1", "reserved_2")

# Hard cap for a single secret. Also the size of each output buffer.
MAX_LEN = 128

PROBE_MAGIC = 0x5EC0DE


def xor_mask(index: int, base: int) -> int:
    """Per-index XOR mask. Must stay in sync with se_decode() in the C output."""
    return (base + index * 37 + ((index & 7) << 1)) & 0xFF


def encode(data: bytes, base: int) -> list[int]:
    return [b ^ xor_mask(i, base) for i, b in enumerate(data)]


def c_assignments(values: list[int], indent: str = "    ") -> str:
    lines = []
    for i, v in enumerate(values):
        lines.append("%sp[%d] = 0x%02X;" % (indent, i, v))
    return "\n".join(lines)


def build_source(slots: list[bytes], bases: list[int]) -> str:
    n_slots = len(SLOT_ORDER)
    out = []
    out.append("/*")
    out.append(" * AUTO-GENERATED by Packager/Secrets/gen_source.py -- DO NOT EDIT.")
    out.append(" *")
    out.append(" * Native secret store. Secrets are NOT stored as string literals:")
    out.append(" * each byte is XOR-masked and written by a fill function at runtime,")
    out.append(" * so no plaintext blob exists in .rodata.")
    out.append(" */")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("")
    out.append("#if defined(_WIN32) || defined(_WIN64)")
    out.append("#  define SE_API __declspec(dllexport)")
    out.append("#else")
    out.append("#  define SE_API __attribute__((visibility(\"default\")))")
    out.append("#endif")
    out.append("")
    out.append("#define SE_MAX_LEN %d" % MAX_LEN)
    out.append("#define SE_SLOTS   %d" % n_slots)
    out.append("#define SE_MAGIC   0x%X" % PROBE_MAGIC)
    out.append("")

    out.append("/*")
    out.append(" * One buffer per slot. The Lua side reads the returned pointer")
    out.append(" * immediately and copies it into a Lua string, so a shared buffer")
    out.append(" * would work too -- but per-slot buffers keep two secrets live at")
    out.append(" * the same time without clobbering each other.")
    out.append(" */")
    for i in range(n_slots):
        out.append("static char se_buf_%d[SE_MAX_LEN];" % i)
        out.append("static int  se_len_%d = 0;" % i)
    out.append("")

    for i, data in enumerate(slots):
        if not data:
            continue
        vals = encode(data, bases[i])
        out.append("static void se_fill_%d(unsigned char *p)" % i)
        out.append("{")
        out.append(c_assignments(vals))
        out.append("}")
        out.append("")

    out.append("/*")
    out.append(" * Inverse of the mask applied by gen_source.py. The seed is baked")
    out.append(" * in per slot at generation time.")
    out.append(" */")
    out.append("static void se_decode(unsigned char *p, int n, unsigned base)")
    out.append("{")
    out.append("    int i;")
    out.append("    for (i = 0; i < n; ++i) {")
    out.append("        p[i] = (unsigned char)(p[i] ^ (unsigned char)"
               "(base + i * 37 + ((i & 7) << 1)));")
    out.append("    }")
    out.append("}")
    out.append("")

    out.append("static const unsigned se_base[%d] = {" % n_slots)
    out.append("    " + ", ".join("0x%Xu" % b for b in bases))
    out.append("};")
    out.append("")

    out.append("static void se_materialise(int slot)")
    out.append("{")
    out.append("    unsigned char *p;")
    out.append("    switch (slot) {")
    for i, data in enumerate(slots):
        if not data:
            continue
        out.append("    case %d:" % i)
        out.append("        if (se_len_%d) return;" % i)
        out.append("        p = (unsigned char *)se_buf_%d;" % i)
        out.append("        se_fill_%d(p);" % i)
        out.append("        se_len_%d = %d;" % (i, len(data)))
        out.append("        se_decode(p, %d, se_base[%d]);" % (len(data), i))
        out.append("        p[%d] = 0;" % len(data))
        out.append("        break;")
    out.append("    default:")
    out.append("        break;")
    out.append("    }")
    out.append("}")
    out.append("")

    out.append("/* Returns the secret for `slot`, or NULL when unset / unknown. */")
    out.append("SE_API const char *se_cfg(int slot)")
    out.append("{")
    out.append("    if (slot < 0 || slot >= SE_SLOTS) return NULL;")
    out.append("    se_materialise(slot);")
    out.append("    switch (slot) {")
    for i in range(n_slots):
        out.append("    case %d: return se_len_%d ? se_buf_%d : NULL;" % (i, i, i))
    out.append("    }")
    out.append("    return NULL;")
    out.append("}")
    out.append("")
    out.append("/* Lets the caller verify it loaded the right library. */")
    out.append("SE_API int se_cfg_probe(void)")
    out.append("{")
    out.append("    return SE_MAGIC;")
    out.append("}")
    out.append("")

    return "\n".join(out)


def load_slots(path: str) -> list[bytes]:
    with open(path, "r", encoding="utf-8") as fh:
        raw = json.load(fh)
    if not isinstance(raw, dict):
        raise SystemExit("secrets file must be a JSON object")

    slots = []
    for name in SLOT_ORDER:
        value = raw.get(name, "")
        if value is None:
            value = ""
        if not isinstance(value, str):
            raise SystemExit("slot '%s' must be a string" % name)
        data = value.encode("utf-8")
        if len(data) >= MAX_LEN:
            raise SystemExit("slot '%s' is too long (max %d bytes, got %d)"
                             % (name, MAX_LEN - 1, len(data)))
        slots.append(data)

    if not any(slots):
        raise SystemExit("no non-empty slot found; nothing to embed")
    return slots


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--input", default=os.path.join(here, "secrets.local.json"),
                    help="JSON file holding the plaintext secrets")
    ap.add_argument("--output", default=os.path.join(here, "build", "secrets.c"),
                    help="path of the generated C source")
    ap.add_argument("--seed", type=int, default=None,
                    help="fixed RNG seed (builds become reproducible)")
    args = ap.parse_args()

    if not os.path.isfile(args.input):
        raise SystemExit(
            "secrets file not found: %s\n"
            "Copy secrets.local.example.json to secrets.local.json and fill it in."
            % args.input
        )

    rng = random.Random(args.seed) if args.seed is not None else random.SystemRandom()
    slots = load_slots(args.input)
    bases = [rng.randrange(0, 256) for _ in SLOT_ORDER]

    source = build_source(slots, bases)

    out_dir = os.path.dirname(os.path.abspath(args.output))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(source)

    filled = [SLOT_ORDER[i] for i, s in enumerate(slots) if s]
    print("generated %s" % args.output)
    print("  slots embedded: %s" % ", ".join(filled))
    print("  bytes of source: %d" % len(source))
    return 0


if __name__ == "__main__":
    sys.exit(main())
